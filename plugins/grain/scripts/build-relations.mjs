#!/usr/bin/env node
// Vendors the relation-extraction machinery from the Yggdrasil repository (same author, MIT) into
// engine/vendor/relations/ as plain ESM: per-language dependency extractors (tree-sitter tree → declared symbols +
// ordered candidate groups), the language-partitioned symbol table, the tri-state resolver (resolved / ambiguous /
// absent — silence instead of a false edge), and the per-language path resolvers (TS relative/index, Python module
// roots, Go module tree, Java source roots, PHP PSR-4, Rust crate tree, C/C++ quoted includes, Ruby require_relative).
//
//   node scripts/build-relations.mjs [path-to-Yggdrasil]      (default: GRAIN_YGG_DIR, else ../../../Yggdrasil)
//
// TypeScript is erased with node:module's stripTypeScriptTypes (mode 'transform' — handles enums), import specifiers
// are rewritten .js → .mjs, and the Yggdrasil-model-coupled tail of resolve-path.ts (guardedResolve + its Graph /
// repo-scanner imports) is cut: grain supplies its own ownerOf/isExcluded. The generated files are committed; this
// script exists to regenerate them against a newer Yggdrasil checkout.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stripTypeScriptTypes } from 'node:module';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(process.argv[2] || process.env.GRAIN_YGG_DIR || join(here, '..', '..', '..', '..', 'Yggdrasil'), 'source/cli/src/relations');
const OUT = join(here, '..', 'engine', 'vendor', 'relations');
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', SRC, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim(); } catch {}

const FILES = ['symbol-table.ts', 'resolver.ts', 'resolve-path.ts',
  ...readdirSync(join(SRC, 'extractors')).filter(f => f.endsWith('.ts')).map(f => 'extractors/' + f)];

mkdirSync(join(OUT, 'extractors'), { recursive: true });
// the one helper the extractors pull from Yggdrasil's ast module: a 20-line pure tree walk
{
  const src = readFileSync(join(SRC, '..', 'ast', 'walk.ts'), 'utf8');
  const js = stripTypeScriptTypes(src, { mode: 'transform', sourceMap: false });
  writeFileSync(join(OUT, 'walk.mjs'), `// GENERATED by scripts/build-relations.mjs — Yggdrasil ${commit} source/cli/src/ast/walk.ts (MIT, same author).\n` + js);
  console.log('vendored ast/walk.ts');
}
for (const rel of FILES) {
  let src = readFileSync(join(SRC, rel), 'utf8');
  src = src.replace(/from '\.\.\/\.\.\/ast\/walk\.js'/g, "from '../walk.js'");
  if (rel === 'resolve-path.ts') {
    // cut the Yggdrasil-graph-coupled wrapper; everything above it is pure filesystem + per-language resolvers
    const cut = src.indexOf('export async function guardedResolve(');
    if (cut < 0) { console.error('guardedResolve anchor missing — resolve-path.ts layout changed, re-check the cut'); process.exit(1); }
    const head = src.slice(0, cut);
    const tailStart = src.indexOf('\n}', cut); // end of guardedResolve
    src = head + src.slice(src.indexOf('\n', tailStart + 2) + 1);
    src = src.split('\n').filter(l => !/from '\.\.\/(io|model)\//.test(l) && !/from '\.\/owner-index\.js'/.test(l)).join('\n');
  }
  let js = stripTypeScriptTypes(src, { mode: 'transform', sourceMap: false });
  js = js.replace(/(from\s+['"])(\.{1,2}\/[^'"]+)\.js(['"])/g, '$1$2.mjs$3');
  const header = `// GENERATED by scripts/build-relations.mjs — do not edit.\n// Source: Yggdrasil ${commit} source/cli/src/relations/${rel} (MIT, same author). Regenerate: node scripts/build-relations.mjs\n`;
  writeFileSync(join(OUT, rel.replace(/\.ts$/, '.mjs')), header + js);
  console.log('vendored', rel);
}
console.log('done →', OUT);
